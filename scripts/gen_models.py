#!/usr/bin/env python3
"""Simple 3D models for the parts KiCad's bundled library has none for.

Honest stand-ins, not vendor CAD: a box the size of the real body, plus a
barrel for the BNCs.  They exist so the 3D render shows the board as it will
look, and so nothing renders as bare pads.

VRML, with KiCad's convention of 1 model unit = 2.54 mm: the footprint entries
carry a scale of 1/2.54 and the geometry here is plain millimetres.  In the
model frame X is board +X, Y is board -Y and Z is up out of the board.
(From the op-amp board's scripts/gen_models.py.)
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, "..", "hardware", "lib", "earthnmr.3dshapes"))
MM = 1.0 / 2.54

HEAD = "#VRML V2.0 utf8\n# Generated by scripts/gen_models.py -- a plain stand-in body.\n"


def material(r, g, b, shininess=0.3):
    return (f"appearance Appearance {{ material Material {{ "
            f"diffuseColor {r} {g} {b} specularColor 0.2 0.2 0.2 "
            f"shininess {shininess} }} }}")


def box(cx, cy, cz, sx, sy, sz, colour):
    return (f"Transform {{ translation {cx:.4f} {cy:.4f} {cz:.4f} children [\n"
            f"  Shape {{ {material(*colour)}\n"
            f"    geometry Box {{ size {sx:.4f} {sy:.4f} {sz:.4f} }} }} ] }}\n")


def prism_x(x0, x1, cy, cz, radius, colour, sides=16):
    """A prism along the board's X axis, as explicit faces (KiCad's VRML reader
    does not draw the Cylinder primitive)."""
    pts = []
    for x in (x0, x1):
        for i in range(sides):
            a = 2 * math.pi * i / sides
            pts.append((x, cy + radius * math.cos(a), cz + radius * math.sin(a)))
    coords = ", ".join(f"{p[0]:.4f} {p[1]:.4f} {p[2]:.4f}" for p in pts)
    faces = []
    for i in range(sides):
        j = (i + 1) % sides
        faces.append(f"{i} {j} {j + sides} {i + sides} -1")
    faces.append(" ".join(str(i) for i in range(sides)) + " -1")
    faces.append(" ".join(str(i + sides) for i in reversed(range(sides))) + " -1")
    return ("Shape {\n  " + material(*colour) + "\n"
            "  geometry IndexedFaceSet {\n"
            "    creaseAngle 1.0 solid TRUE\n"
            f"    coord Coordinate {{ point [ {coords} ] }}\n"
            f"    coordIndex [ {' '.join(faces)} ]\n"
            "  } }\n")


def prism_z(cx, cy, z0, z1, radius, colour, sides=16):
    """A prism standing up out of the board (a screw head, a pin)."""
    pts = []
    for z in (z0, z1):
        for i in range(sides):
            a = 2 * math.pi * i / sides
            pts.append((cx + radius * math.cos(a), cy + radius * math.sin(a), z))
    coords = ", ".join(f"{p[0]:.4f} {p[1]:.4f} {p[2]:.4f}" for p in pts)
    faces = []
    for i in range(sides):
        j = (i + 1) % sides
        faces.append(f"{i} {j} {j + sides} {i + sides} -1")
    faces.append(" ".join(str(i) for i in reversed(range(sides))) + " -1")
    faces.append(" ".join(str(i + sides) for i in range(sides)) + " -1")
    return ("Shape {\n  " + material(*colour) + "\n"
            "  geometry IndexedFaceSet {\n"
            "    creaseAngle 1.0 solid TRUE\n"
            f"    coord Coordinate {{ point [ {coords} ] }}\n"
            f"    coordIndex [ {' '.join(faces)} ]\n"
            "  } }\n")


SILVER = (0.52, 0.54, 0.57)
BLUE = (0.10, 0.18, 0.55)
TERMBLUE = (0.12, 0.30, 0.70)


def bnc():
    """Body 10 x 10 x 12.2 mm on the board, barrel on +X, axis 6.1 mm up."""
    s = HEAD
    s += box(0, 0, 6.1, 10.0, 10.0, 12.2, SILVER)
    s += prism_x(5.0, 19.5, 0, 6.1, 4.8, SILVER)
    s += prism_x(19.5, 23.0, 0, 6.1, 6.0, SILVER, sides=6)
    s += prism_x(23.0, 24.5, 0, 6.1, 4.0, SILVER)
    s += prism_x(6.0, 24.5, 0, 6.1, 0.6, (0.85, 0.7, 0.3))
    return "BNC_KYWE_RightAngle.wrl", s


def trimpot():
    """BOCHEN 3362P: 6.9 x 7.1 mm, 4.8 mm tall, screw on top.  The body's middle
    is 1.30 mm from the pins' middle toward pins 1 and 3 (y_fp = +1.30, so
    y_model = -1.30), the screw 3.2 mm from the edge beside pin 2 (y_fp = +0.95)."""
    s = HEAD
    s += box(0, -1.30, 2.4, 6.9, 7.1, 4.8, BLUE)
    s += prism_z(0, -0.95, 4.8, 5.2, 1.7, (0.85, 0.85, 0.88))
    s += box(0, -0.95, 5.25, 2.4, 0.6, 0.2, (0.25, 0.25, 0.28))
    return "Potentiometer_3362P.wrl", s


def kf301(n):
    """KEFA KF301-5.0-nP: n x 5.0 mm wide, 7.6 mm deep, 10.0 mm tall, blue.

    Pins at y = 0 in the footprint; the body runs from y = -3.7 (the sloped
    wire-entry face) to y = +4.0 (the vertical back), from the KF301-5.0
    drawing's side view (pins 4.0 mm from the back face).  In the model frame
    Y is -y."""
    w = n * 5.0 + 0.4
    s = HEAD
    s += box(0, -0.15, 5.0, w, 7.7, 10.0, TERMBLUE)      # y_model = -(y_fp); centre at y_fp = +0.15
    for i in range(n):
        x = (i - (n - 1) / 2.0) * 5.0
        s += prism_z(x, -0.15, 10.0, 10.3, 1.6, SILVER)   # screw heads
        s += box(x, 3.75, 3.0, 3.0, 0.1, 3.0, (0.05, 0.05, 0.05))  # wire openings on the -y face
    return f"TerminalBlock_KF301_1x{n:02d}.wrl", s


def slide_switch():
    """Shouhan MSK12C02: 6.6 x 2.7 mm body, 1.4 mm tall, pins toward -y in the
    footprint; the knob, 1.3 mm wide, sticks out 1.45 mm from the +y edge
    (y_model -1.35 to -2.8) and slides +-0.8 mm about the middle."""
    s = HEAD
    s += box(0, 0, 0.7, 6.6, 2.7, 1.4, (0.15, 0.15, 0.15))        # the body
    s += box(0.8, -2.075, 0.7, 1.3, 1.45, 0.9, (0.92, 0.92, 0.92))   # the knob, at the 1 end of its travel
    return "SW_MSK12C02.wrl", s


def fuse_2920():
    """A 2920 chip PTC: 7.5 x 5.1 mm, 1.6 mm tall, pale yellow (KiCad ships no
    model for Fuse_2920_7451Metric)."""
    s = HEAD
    s += box(0, 0, 0.8, 7.5, 5.1, 1.6, (0.85, 0.8, 0.45))
    s += box(-3.3, 0, 0.8, 0.9, 5.1, 1.62, SILVER)
    s += box(3.3, 0, 0.8, 0.9, 5.1, 1.62, SILVER)
    return "Fuse_2920.wrl", s


def film_mes():
    """Hongzhi MES105J2A: a box 7.2 x 6.0 mm and 12.0 mm tall over its leads on 5 mm."""
    s = HEAD
    s += box(0, 0, 6.0 + 0.3, 7.2, 6.0, 12.0, (0.75, 0.15, 0.12))
    return "C_Film_L7.2_W6.0.wrl", s


def dip8():
    """KingTek DSIC08: 20.3 x 6.2 mm, 3.6 mm tall, red, eight white sliders."""
    s = HEAD
    s += box(0, 0, 1.8, 20.32, 6.2, 3.6, (0.75, 0.1, 0.1))
    for i in range(8):
        x = -2.54 * 3.5 + i * 2.54
        s += box(x, -0.6, 3.75, 1.2, 1.4, 0.3, (0.95, 0.95, 0.95))   # each slider, toward ON (pads 1-8, +y_fp)
    return "SW_DIP_x08_DSIC08.wrl", s


def testloop():
    """RH-5019: a 3.8 mm long wire loop, 2.0 mm wide, standing 1.5 mm up."""
    s = HEAD
    s += box(0, 0, 0.05, 3.8, 2.0, 0.1, SILVER)                 # the feet
    s += box(-1.65, 0, 0.9, 0.5, 2.0, 1.6, SILVER)             # the two uprights
    s += box(1.65, 0, 0.9, 0.5, 2.0, 1.6, SILVER)
    s += box(0, 0, 1.6, 3.8, 0.5, 0.5, SILVER)                 # the bar a hook grabs
    return "TestLoop_RH-5019.wrl", s


def main():
    os.makedirs(OUT, exist_ok=True)
    for maker in (bnc, trimpot, testloop, lambda: kf301(2), lambda: kf301(3), slide_switch, fuse_2920,
                  film_mes, dip8):
        name, body = maker()
        with open(os.path.join(OUT, name), "w") as fh:
            fh.write(body)
        print(f"  wrote {os.path.relpath(os.path.join(OUT, name))}")


if __name__ == "__main__":
    main()
